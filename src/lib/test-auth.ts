/**
 * Create mock React Query result
 */
export function createMockQueryResult<T>(data: T, options: {
  isLoading?: boolean;
  error?: Error | null;
  isSuccess?: boolean;
  isError?: boolean;
} = {}) {
  return {
    data,
    isLoading: options.isLoading ?? false,
    error: options.error ?? null,
    isSuccess: options.isSuccess ?? true,
    isError: options.isError ?? false,
    isPending: options.isLoading ?? false,
    status: options.isLoading ? 'pending' : options.isError ? 'error' : 'success',
    refetch: () => Promise.resolve(),
  };
}

/**
 * Mock useVoilaApi hook
 */
