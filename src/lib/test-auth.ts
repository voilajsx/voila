let cachedTokens: AuthTokens | null = null;

/**
 * Parse .env.auth file and extract TEST tokens for development/testing
 * This reads test tokens generated by `npm run generate tokens`
 * WARNING: Only for development/testing - not for production use
 */
export function loadAuthTokens(envAuthPath?: string): AuthTokens {
  if (cachedTokens) {
    return cachedTokens;
  }

  let authFilePath = envAuthPath;
  
  if (!authFilePath) {
    if (typeof process !== 'undefined' && process.cwd) {
      authFilePath = join(process.cwd(), '.env.auth');
    } else if (typeof window !== 'undefined') {
      throw new Error('Browser environment requires envAuthPath parameter or build-time token injection');
    } else {
      throw new Error('Unable to auto-detect .env.auth file location');
    }
  }

  // Skip file reading in browser environment
  if (typeof window !== 'undefined') {
    throw new Error('Browser environment: Auth tokens should be provided via environment variables or build-time injection');
  }

  if (!readFileSync) {
    throw new Error('File system not available in this environment');
  }

  try {
    const authFileContent = readFileSync(authFilePath, 'utf-8');
    const tokens: Partial<AuthTokens> = {};
    
    authFileContent.split('\n').forEach(line => {
      const trimmedLine = line.trim();
      if (!trimmedLine || trimmedLine.startsWith('#')) return;
      
      const equalIndex = trimmedLine.indexOf('=');
      if (equalIndex === -1) return;
      
      const key = trimmedLine.substring(0, equalIndex).trim();
      const value = trimmedLine.substring(equalIndex + 1).trim();
      
      if (key in TOKEN_METADATA) {
        (tokens as any)[key] = value;
      }
    });
    
    // Validate all tokens are present, fill missing with defaults
    const missingTokens = Object.keys(TOKEN_METADATA).filter(key => !tokens[key as TokenName]);
    
    if (missingTokens.length > 0) {
      console.warn(`⚠️ Missing tokens in .env.auth: ${missingTokens.join(', ')}`);
      console.warn('💡 Run: npm run generate tokens');
      
      // Fill missing with fallback tokens
      missingTokens.forEach(key => {
        (tokens as any)[key] = getFallbackTokens()[key as TokenName];
      });
    }
    
    cachedTokens = tokens as AuthTokens;
    return cachedTokens;
    
  } catch (error) {
    console.error('❌ Failed to read .env.auth file:', error);
    console.log('🔄 Using fallback development tokens');
    console.log('💡 Run: npm run generate tokens');
    
    cachedTokens = getFallbackTokens();
    return cachedTokens;
  }
}

/**
 * Get specific token by name
 */
export function getAuthToken(tokenName: TokenName, envAuthPath?: string): string {
  // Browser environment - use Vite environment variables
  if (typeof window !== 'undefined') {
    const browserTokens: AuthTokens = {
      'WEBHOOK_SERVICE_API_TOKEN': import.meta.env.VITE_WEBHOOK_SERVICE_API_TOKEN,
      'USER_BASIC': import.meta.env.VITE_USER_BASIC,
      'ADMIN_TENANT': import.meta.env.VITE_ADMIN_TENANT,
      'ADMIN_SYSTEM': import.meta.env.VITE_ADMIN_SYSTEM,
      'ADMIN_ORG': import.meta.env.VITE_ADMIN_ORG,
      'MODERATOR_MANAGE': import.meta.env.VITE_MODERATOR_MANAGE,
      'MODERATOR_APPROVE': import.meta.env.VITE_MODERATOR_APPROVE,
      'MODERATOR_REVIEW': import.meta.env.VITE_MODERATOR_REVIEW,
      'USER_MAX': import.meta.env.VITE_USER_MAX,
      'USER_PRO': import.meta.env.VITE_USER_PRO
    };
    return browserTokens[tokenName];
  }
  
  const tokens = loadAuthTokens(envAuthPath);
  return tokens[tokenName];
}

